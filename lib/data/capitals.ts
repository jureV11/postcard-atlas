/** Posted in (or within 15 km of) its country's capital. */
export function isCapital(countryCode: string, lat: number, lng: number): boolean {
  return (CAPITALS.get(countryCode.toUpperCase()) ?? []).some(([la, ln]) => haversineKm(lat, lng, la, ln) <= 15);
}
